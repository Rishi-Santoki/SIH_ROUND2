from fastapi import APIRouter, Depends, HTTPException
from supabase import Client
from app.dependencies import get_current_recruiter
from app.models.industry_schemas import CompanyUpdate, RecruiterInvite

router = APIRouter(prefix="/industry/company", tags=["Industry Company"])

@router.get("")
def get_company(recruiter: dict = Depends(get_current_recruiter)):
    client: Client = recruiter["client"]
    company_id = recruiter["company_id"]
    if not company_id:
        raise HTTPException(status_code=404, detail="No company associated with this recruiter")
        
    res = client.table("companies").select("*").eq("company_id", company_id).execute()
    if not res.data:
        raise HTTPException(status_code=404, detail="Company not found")
        
    # Join with latest verification request
    v_res = client.table("verification_requests").select("*").eq("entity_type", "company").eq("entity_id", company_id).order("created_at", desc=True).limit(1).execute()
    
    company_data = res.data[0]
    company_data["latest_verification_request"] = v_res.data[0] if v_res.data else None
    return company_data

@router.patch("")
def update_company(update: CompanyUpdate, recruiter: dict = Depends(get_current_recruiter)):
    if not recruiter.get("is_primary_contact"):
        raise HTTPException(status_code=403, detail="Only the primary contact can update the company profile")
        
    client: Client = recruiter["client"]
    data = update.model_dump(exclude_unset=True)
    
    if "logo_url" in data:
        from app.services.storage_service import delete_file
        res = client.table("companies").select("logo_url").eq("company_id", recruiter["company_id"]).execute()
        if res.data and res.data[0].get("logo_url"):
            old_url = res.data[0]["logo_url"]
            if old_url != data["logo_url"]:
                # The user_id isn't directly the owner here (company_id is), but standard delete applies.
                # Since public buckets often just have the user_id as the first path, we assume the logo path 
                # was generated by the primary contact. Delete it via the service client to bypass RLS if needed,
                # but standard db client works if RLS allows it.
                delete_file(client, "company-logos", old_url)
                
    res = client.table("companies").update(data).eq("company_id", recruiter["company_id"]).execute()
    return res.data

@router.post("/verify")
def request_verification(recruiter: dict = Depends(get_current_recruiter)):
    client: Client = recruiter["client"]
    company_id = recruiter["company_id"]
    
    # Check if pending request exists
    existing = client.table("verification_requests").select("status").eq("entity_type", "company").eq("entity_id", company_id).eq("status", "pending").execute()
    if existing.data:
        raise HTTPException(status_code=400, detail="A verification request is already pending")
        
    data = {
        "entity_type": "company",
        "entity_id": company_id,
        "submitted_by": recruiter["user_id"],
        "status": "pending"
    }
    res = client.table("verification_requests").insert(data).execute()
    return res.data

